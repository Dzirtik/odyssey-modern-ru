const makeBook = (book, lineCount, sections) => {
  const note = noteBlueprints[book];
  const notePassage = note ? sections[note[0]] : undefined;
  return {
    book,
    title: `Песнь ${["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII", "XIV", "XV", "XVI", "XVII", "XVIII", "XIX", "XX", "XXI", "XXII", "XXIII", "XXIV"][book - 1]}`,
    sourceRange: `Hom. Od. ${book}.1–${lineCount}`,
    lineCount,
    baseSourceId: "homer_odyssey_perseus_grc1",
    status: "draft",
    humanReviewed: false,
    reviewedAt: "",
    lastFactCheck: "2026-07-24",
    lastRightsCheck: "2026-07-24",
    passages: sections.map(([lineStart, lineEnd, text], index) => ({
      id: `lines-${lineStart}-${lineEnd}`,
      lines: `${book}.${lineStart}–${lineEnd}`,
      lineStart,
      lineEnd,
      paragraphs: [text],
      sequence: index + 1,
    })),
    notes: note
      ? [
          {
            id: `note-book-${String(book).padStart(2, "0")}`,
            anchor: `lines-${notePassage[0]}-${notePassage[1]}`,
            title: note[1],
            summary: note[2],
            details: note[3],
            layer: note[4],
            confidence: note[5],
            sourceIds: ["homer_odyssey_perseus_grc1"],
          },
        ]
      : [],
  };
};

